/**
 * Snapshots the OpenAPPA policy repository template into the backend, so setup
 * can start a repository where the template itself is unreachable (GitHub
 * Enterprise Server, air-gapped installs). The template repository stays the
 * source of truth; this pins the commit a release ships.
 *
 *   pnpm update:openappa-template [ref] [output-path]
 *
 * `ref` defaults to the template's default branch. GH_TOKEN, when set, lifts
 * GitHub's anonymous rate limit.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const TEMPLATE_REPO = "archestra-ai/openappa-config";
const ref = process.argv[2] || "HEAD";
const outputPath =
  process.argv[3] ??
  fileURLToPath(
    new URL("../src/openappa/template.generated.ts", import.meta.url),
  );

const headers = {
  Accept: "application/vnd.github+json",
  "X-GitHub-Api-Version": "2022-11-28",
  ...(process.env.GH_TOKEN
    ? { Authorization: `Bearer ${process.env.GH_TOKEN}` }
    : {}),
};

async function github(path, accept) {
  const response = await fetch(`https://api.github.com${path}`, {
    headers: accept ? { ...headers, Accept: accept } : headers,
  });
  if (!response.ok)
    throw new Error(`GitHub returned HTTP ${response.status} for ${path}`);
  return accept ? response.text() : response.json();
}

const commit = await github(
  `/repos/${TEMPLATE_REPO}/commits/${encodeURIComponent(ref)}`,
);
const tree = await github(
  `/repos/${TEMPLATE_REPO}/git/trees/${commit.sha}?recursive=1`,
);
if (tree.truncated) throw new Error("The template tree is too large");

const files = [];
for (const entry of tree.tree) {
  if (entry.type !== "blob") continue;
  if (entry.mode !== "100644")
    throw new Error(`Unsupported file mode ${entry.mode} for ${entry.path}`);
  files.push({
    path: entry.path,
    content: await github(
      `/repos/${TEMPLATE_REPO}/contents/${entry.path.split("/").map(encodeURIComponent).join("/")}?ref=${commit.sha}`,
      "application/vnd.github.raw+json",
    ),
  });
}
// README first: an empty repository accepts only a single-file write to start.
files.sort((a, b) =>
  a.path === "README.md" ? -1 : b.path === "README.md" ? 1 : a.path.localeCompare(b.path),
);

writeFileSync(
  outputPath,
  `// Generated by \`pnpm update:openappa-template\`. Do not edit.
// The template repository is the source of truth; this pins what a release ships.

export const OPENAPPA_TEMPLATE = ${JSON.stringify(
    { repo: TEMPLATE_REPO, commit: commit.sha, files },
    null,
    2,
  )} as const;
`,
);
console.log(
  `OpenAPPA template pinned to ${TEMPLATE_REPO}@${commit.sha.slice(0, 7)} (${files.length} files)`,
);
